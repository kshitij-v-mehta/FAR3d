! 2D plotter for FAR3d: converts one field of a restart dataset (fs*.bp) to a
! point mesh in cylindrical (R,Z) geometry and writes it as a VisIt/Silo file.
!
!   init_value_plotter [fs0000z.bp] [variable] [zonal] [geom_bzr_to_cyl.bp]
!
!     variable  1 psi, 2 phi (default), 3 pressure, 4 n_fast, 5 v_fast_parallel,
!               6 vth_parallel
!     zonal     1 (default) plots the radial derivative of the n=0 part only
!               (zonal plots); 0 plots the full mode structure
!
! Replaces init_value_run_plotter_new.f90 (see old/). That program carried a
! copy of most of FAR3d to read the positional binary restart file; here the
! few quantities needed (mj, lmax, mm, nn, the field, and the Boozer->cylinder
! geometry) are read by name from the ADIOS2 files, so no `in` file is needed.
! The Boozer->cylinder construction and the Silo output are unchanged.
!
! Outputs: 2D_<field>.silo (VisIt), matlb_2D (x z value text table),
! bound.curve (outer surface), zonal_at_z0.dat (zonal plots only).

program init_value_plotter

  use bp_read_mod

  implicit none
  include "silo_include.inc"   ! generated by build_plotter.sh: silo_f9x.inc (Silo >= 4.11) or silo.inc

  integer :: nargs, variable, zonal_plot, mj, lmax, mjbz, lbmax, lasym_i
  character(len=256) :: arg, fsfile, geomfile
  integer, allocatable :: mm(:), nn(:), signl(:), mmbz(:), nnbz(:)
  double precision, allocatable :: fld(:,:), plot_var(:,:), rderiv(:)
  double precision, allocatable :: rmnc(:,:), zmns(:,:), rho_d(:), q_d(:)
  double precision, allocatable :: tmp2(:,:)
  character(len=8), parameter :: fldname(6) = [ character(len=8) :: 'psi', 'phi', 'pr', 'nf', 'vprlf', 'vthprlf' ]
  character(len=16), parameter :: silofile(6) = [ character(len=16) :: &
       '2D_psi.silo', '2D_phi.silo', '2D_pressure.silo', '2D_nfast.silo', '2D_vprlf.silo', '2D_vthprl.silo' ]
  character(len=8), parameter :: silovar(6) = [ character(len=8) :: 'psi', 'phi', 'pres', 'nfast', 'vprl', 'vthprl' ]

  integer :: i, j, l, icc, itht, mjp1, ndims, npts, dbfile, err, ierr
  double precision :: twopi, arg_t, zeta, dr
  real, allocatable :: x(:), z(:), phi_plot(:), flux_surfs(:), qcontour(:), xouter(:), zouter(:), tht_p(:)
  real, allocatable :: rad(:), qqz(:), zonal_z0(:)

  twopi = 8.d0*atan(1.d0)

  ! ---- arguments ----
  fsfile = 'fs0000z.bp'; variable = 2; zonal_plot = 1; geomfile = 'geom_bzr_to_cyl.bp'
  nargs = command_argument_count()
  if (nargs >= 1) call get_command_argument(1, fsfile)
  if (nargs >= 2) then
     call get_command_argument(2, arg); read (arg,*) variable
  end if
  if (nargs >= 3) then
     call get_command_argument(3, arg); read (arg,*) zonal_plot
  end if
  if (nargs >= 4) call get_command_argument(4, geomfile)
  if (variable < 1 .or. variable > 6) stop 'variable must be 1..6'
  write (0,'(" READING FROM ",a)') trim(fsfile)
  write (0,'("  PLOTTING 2D ",a," ",a)') trim(fldname(variable)), merge('(zonal)','       ', zonal_plot > 0)

  ! ---- restart dataset: grid size, mode numbers, selected field ----
  call bp_open(trim(fsfile))
  call bp_get_i("mj", mj)
  call bp_get_i("lmax", lmax)
  call bp_get_i1("mm", mm)
  call bp_get_i1("nn", nn)
  call bp_get_r2(trim(fldname(variable)), fld)
  call bp_close
  if (size(mm) < lmax .or. size(fld,1) /= mj+1 .or. size(fld,2) < lmax) &
       stop 'restart dataset: stored array sizes inconsistent with mj/lmax'

  ! signl: +1 sin-type, -1 cos-type, 0 for the m=n=0 mode (as in FAR3d setmod)
  allocate (signl(lmax))
  do l = 1, lmax
     signl(l) = 1
     if (nn(l) < 0 .or. (nn(l) == 0 .and. mm(l) < 0)) signl(l) = -1
     if (nn(l) == 0 .and. mm(l) == 0) signl(l) = 0
  end do

  allocate (plot_var(0:mj,lmax))
  plot_var(:,:) = fld(:,1:lmax)

  if (zonal_plot > 0) then
     allocate (rderiv(0:mj))
     do l = 1, lmax
        do j = 1, mj-1
           dr = 2.d0/dble(mj)
           rderiv(j) = (plot_var(j+1,l) - plot_var(j-1,l))/dr
        end do
        rderiv(0) = (plot_var(1,l) - plot_var(0,l))/(0.5d0*dr)
        rderiv(mj) = (plot_var(mj,l) - plot_var(mj-1,l))/(0.5d0*dr)
        plot_var(:,l) = rderiv(:)
     end do
  end if

  ! ---- geometry dataset: Boozer -> cylindrical (written by FAR3d vmec) ----
  call bp_open(trim(geomfile))
  call bp_get_i("mj", mjbz)
  call bp_get_i("lbmax", lbmax)
  call bp_get_i("lasym", lasym_i)
  call bp_get_i1("mmb", mmbz)
  call bp_get_i1("nnb", nnbz)
  call bp_get_r1("rho", rho_d)
  call bp_get_r1("q", q_d)
  call bp_get_r2("R_eq", rmnc)
  call bp_get_r2("Z_eq", zmns)
  call bp_close
  if (mjbz /= mj) stop 'geometry file mj differs from restart file mj'
  if (lasym_i /= 0) stop 'asymmetric (lasym) geometry is not supported: R_eq/Z_eq only hold the symmetric terms'

  allocate (rad(0:mj), qqz(0:mj))
  rad = real(rho_d)
  qqz = real(q_d)

  ! ---- flux surfaces in 2D cylindrical geometry and the field on them ----
  mjp1 = mj + 1
  itht = 600
  zeta = 0.d0
  allocate (xouter(itht), zouter(itht), tht_p(itht))
  allocate (x(itht*mjp1), z(itht*mjp1), phi_plot(itht*mjp1), flux_surfs(itht*mjp1), qcontour(itht*mjp1))
  allocate (zonal_z0(0:mj))
  x(:) = 0.; z(:) = 0.; phi_plot(:) = 0.

  icc = 0
  do j = 0, mj
     do i = 1, itht
        icc = icc + 1
        tht_p(i) = real(twopi*(real(i-1)/real(itht-1)))
        x(icc) = 0.; z(icc) = 0.

        do l = 1, lbmax
           arg_t = tht_p(i)*real(mmbz(l)) - zeta*real(nnbz(l))
           x(icc) = x(icc) + rmnc(j+1,l)*cos(arg_t)
           z(icc) = z(icc) + zmns(j+1,l)*sin(arg_t)
        end do
        if (j == mj) then
           xouter(i) = x(icc)
           zouter(i) = z(icc)
        end if

        phi_plot(icc) = 0.
        if (zonal_plot == 0) then
           do l = 1, lmax
              arg_t = real(mm(l))*tht_p(i) - zeta*real(nn(l))
              if (signl(l) == 1) then
                 phi_plot(icc) = phi_plot(icc) + plot_var(j,l)*sin(arg_t)
              else if (signl(l) == -1) then
                 phi_plot(icc) = phi_plot(icc) + plot_var(j,l)*cos(arg_t)
              end if
           end do
        else
           do l = 1, lmax
              if (nn(l) == 0) then
                 arg_t = real(mm(l))*tht_p(i)
                 if (signl(l) == 1) then
                    phi_plot(icc) = phi_plot(icc) + plot_var(j,l)*sin(arg_t)
                 else if (signl(l) == -1) then
                    phi_plot(icc) = phi_plot(icc) + plot_var(j,l)*cos(arg_t)
                 end if
              end if
           end do
        end if
        flux_surfs(icc) = real(rad(j))/real(rad(mj))
        qcontour(icc) = qqz(j)
        if (i == 1 .and. zonal_plot /= 0) zonal_z0(j) = phi_plot(icc)
     end do
  end do

  if (zonal_plot /= 0) then
     open (unit=87, file='zonal_at_z0.dat', status='unknown')
     do j = 0, mj
        write (87,'(e15.8,2x,e15.8)') rad(j), zonal_z0(j)
     end do
     close (unit=87)
  end if

  ! ---- Silo (VisIt) file ----
  err = dbcreate(trim(silofile(variable)), len_trim(silofile(variable)), DB_CLOBBER, DB_LOCAL, &
       "Comment about the data", 22, DB_PDB, dbfile)
  if (err /= 0) stop 27
  ndims = 2; npts = itht*mjp1
  err = dbputpm(dbfile, "pointmesh", 9, ndims, x, z, DB_F77NULL, npts, DB_FLOAT, DB_F77NULL, ierr)
  if (ierr /= 0) stop 28
  err = dbputpv1(dbfile, trim(silovar(variable)), len_trim(silovar(variable)), "pointmesh", 9, phi_plot, npts, &
       DB_FLOAT, DB_F77NULL, ierr)
  if (ierr /= 0) stop 29
  err = dbputpv1(dbfile, "flux", 4, "pointmesh", 9, flux_surfs, npts, DB_FLOAT, DB_F77NULL, ierr)
  if (ierr /= 0) stop 30
  err = dbputpv1(dbfile, "q", 1, "pointmesh", 9, qcontour, npts, DB_FLOAT, DB_F77NULL, ierr)
  if (ierr /= 0) stop 30
  err = dbclose(dbfile)

  open (unit=15, file="bound.curve", status="unknown")
  do i = 1, itht
     write (15,'(f10.7,2x,f10.7)') xouter(i), zouter(i)
  end do
  close (15)

  open (unit=17, file="matlb_2D", status="unknown")
  do i = 1, npts
     write (17,'(e15.8,2(2x,e15.8))') x(i), z(i), phi_plot(i)
  end do
  close (unit=17)

end program init_value_plotter
